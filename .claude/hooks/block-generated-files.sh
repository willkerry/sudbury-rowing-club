#!/usr/bin/env bash
# PreToolUse: exit 2 blocks the edit and hands stderr to Claude as the reason.

file=$(jq -r '.tool_input.file_path // empty')
[[ -n $file ]] || exit 0

block() {
  echo "Blocked: $file $1" >&2
  exit 2
}

tracked() {
  git -C "$(dirname "$file")" ls-files --error-unmatch "$file" >/dev/null 2>&1
}

case $file in
  */worker-configuration.d.ts)
    block "is generated by \`pnpm generate\` (wrangler types). Change wrangler.jsonc and regenerate." ;;
  */packages/weathericons/src/generated/*)
    block "is generated by \`pnpm --filter @sudburyrc/weathericons generate\`. Change the SVGR config or scripts/ instead." ;;
  */packages/weathericons/vendor/*)
    block "is in the met.no submodule. Don't edit upstream files." ;;
  */packages/static/schemas/*)
    block "is generated from src/clubs.ts by \`pnpm --filter @sudburyrc/static generate-schemas\`." ;;
  *.gen.ts | */dist/*)
    block "is build output. Change its source and rebuild." ;;
  */pnpm-lock.yaml)
    block "is managed by pnpm. Use \`pnpm add\`, \`pnpm remove\` or \`pnpm install\`." ;;
  */packages/db/migrations/meta/*)
    block "is drizzle-kit's snapshot. Change packages/db/src and run \`pnpm --filter @sudburyrc/db db:generate\`." ;;
  */packages/db/migrations/*)
    tracked && block "is a committed migration, which may already be applied to D1. Add a new one with \`pnpm --filter @sudburyrc/db db:generate\` (or \`db:generate --custom\` for hand-written SQL)." ;;
  */apps/results/data/*)
    tracked && block "is archival results HTML served at its original URL. Fix rendering in the Astro loader or layouts instead." ;;
esac

exit 0
